"""Generate deterministic Lua dictionaries and Roblox import files from reviewed TSV."""
from pathlib import Path
import csv,json
ROOT=Path(__file__).resolve().parent

def generate():
    dictionaries={lang:{} for lang in ('en','ru','uk')}
    with (ROOT/'strings.tsv').open(encoding='utf-8',newline='') as f:
        for row in csv.DictReader(f,delimiter='\t'):
            key=row['key'].strip()
            if key in dictionaries['en']: raise ValueError(f'duplicate localization key: {key}')
            for lang in dictionaries:
                text=row[lang]
                if not text: raise ValueError(f'missing {lang}: {key}')
                dictionaries[lang][key]=text
    lua=['-- Generated by localization/build_locales.py. Edit strings.tsv, then regenerate.','return {']
    for lang,entries in dictionaries.items():
        lua.append('  '+lang+' = {')
        for key,text in sorted(entries.items()):
            lua.append('    ['+json.dumps(key,ensure_ascii=False)+'] = '+json.dumps(text,ensure_ascii=False)+',')
        lua.append('  },')
    lua.append('}')
    (ROOT.parent/'src/Locales.lua').write_text('\n'.join(lua)+'\n',encoding='utf-8')
    (ROOT/'strings.json').write_text(json.dumps(dictionaries,ensure_ascii=False,sort_keys=True,indent=2)+'\n',encoding='utf-8')
    fields=['Key','Source','Context','Example','en-us','ru','es','pt-br','pl','de','fr','tr','ja','ko']
    with (ROOT/'Roblox_Cloud_Import.csv').open('w',encoding='utf-8-sig',newline='') as f:
        writer=csv.DictWriter(f,fieldnames=fields); writer.writeheader()
        for key,text in sorted(dictionaries['en'].items()):
            writer.writerow({'Key':key,'Source':text,'Context':key,'Example':'Touchline Dynasty UI or structured event. Keep {parameters} unchanged.','en-us':text,'ru':dictionaries['ru'][key]})
    # Ukrainian is local, because cloud automatic translation does not support it.
    with (ROOT/'Ukrainian_Manual.csv').open('w',encoding='utf-8-sig',newline='') as f:
        writer=csv.writer(f); writer.writerow(['Key','English','Ukrainian'])
        for key,text in sorted(dictionaries['en'].items()):writer.writerow([key,text,dictionaries['uk'][key]])
    return len(dictionaries['en'])
if __name__=='__main__':print('Generated',generate(),'keys in en / ru / uk')
